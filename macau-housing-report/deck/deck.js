/* ---------- 表格：沿用模板的細紅線列式 ---------- */
function dataTable(s, { x, y, w, head, rows, colW, rowH, align, hi, cap, gut }) {
  let cy = y;
  if (cap) { label(s, cap, { x, y: cy, w, size: 12 }); cy += 0.42; }
  const rh = rowH ?? 0.4;
  const cw = colW || head.map(() => w / head.length);
  const g = gut ?? 0.14;
  const pad = (i) => (i < head.length - 1 ? g : 0);
  let cx = x;
  head.forEach((hd, i) => {
    s.addText(hd, {
      x: cx, y: cy, w: cw[i] - pad(i), h: 0.34, isTextBox: true, margin: 0,
      fontFace: FZH, fontSize: 11, bold: true, color: RED, charSpacing: 0.8,
      align: (align && align[i]) || "left", valign: "middle",
    });
    cx += cw[i];
  });
  cy += 0.38;
  hr(s, x, cy, w, 0.02);
  cy += 0.1;
  rows.forEach((r, ri) => {
    const isHi = hi && hi.includes(ri);
    let rx = x;
    r.forEach((cell, ci) => {
      const numeric = (align && align[ci] === "right");
      const content = Array.isArray(cell)
        ? cell.map((run) => ({
            text: run.text,
            options: {
              fontFace: numeric ? FEN : FZH, fontSize: run.size ?? (isHi ? 13 : 12),
              bold: run.bold ?? isHi, color: RED, breakLine: !!run.br,
            },
          }))
        : String(cell);
      s.addText(content, {
        x: rx, y: cy, w: cw[ci] - pad(ci), h: rh - 0.08, isTextBox: true, margin: 0,
        fontFace: numeric ? FEN : FZH, fontSize: isHi ? 13 : 12,
        bold: isHi, color: RED,
        align: (align && align[ci]) || "left", valign: "middle",
      });
      rx += cw[ci];
    });
    cy += rh - 0.08;
    hr(s, x, cy, w);
    cy += 0.08;
  });
  return cy;
}

